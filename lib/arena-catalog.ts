export function arenaEffectHelp(
  id: string,
): Array<{ term: string; text: string }> {
  const card = arenaCard(id),
    amp = amplifier(id);
  const specific = (notes[id] ?? []).map((text) => ({ term: '细则', text }));
  const text = `${card?.text ?? amp?.text ?? ''}${(notes[id] ?? []).join('')}`;
  const terms = ARENA_TERMS.filter(
    ([term]) =>
      text.includes(term) ||
      (term === '相邻卡牌' && text.includes('相邻武器')) ||
      (term === '直接伤害' && text.includes('伤害后')),
  );
  return [...specific, ...terms.map(([term, text]) => ({ term, text }))];
}
