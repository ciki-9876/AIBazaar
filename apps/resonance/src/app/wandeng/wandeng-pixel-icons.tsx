export type PixelIconName = keyof typeof shapes;
type Props = Omit<SVGProps<SVGSVGElement>, 'name'> & { size?: number | string };
export function PixelIcon({
  name,
  size = 24,
  className = '',
  ...props
}: Props & { name: PixelIconName }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      stroke="none"
      shapeRendering="crispEdges"
      className={`wd-pixel-icon ${className}`}
      {...props}
    >
      <path transform="translate(4 4)" fillRule="evenodd" d={shapes[name]} />
    </svg>
  );
}
const icon = (name: PixelIconName) =>
  function Glyph(props: Props) {
    return <PixelIcon name={name} {...props} />;
  };
